#!/usr/bin/env python3
"""gen_lean43c.py: Lean modules for one case of the certificate from split43's output.
(Case.lean gets the shard facts as one List.Forall term and the range check as its own theorem, which scales to
hundreds of shards.)
usage: gen_lean43c.py PROJECT_DIR DATA_DIR(relative to PROJECT_DIR) MODULE_PREFIX FAMILY(st|reg) FVAL RHO_P RHO_Q
Writes <prefix>/Skel.lean, <prefix>/ShardNNNNN.lean (data + one native_decide theorem each) and <prefix>/Case.lean
(the case theorem CaseOK, from S43.Sound.Case)."""
import os, sys

def fnv1a(b):
    h = 0xcbf29ce484222325
    for x in b:
        h = ((h ^ x) * 0x100000001b3) & 0xFFFFFFFFFFFFFFFF
    return h

proj, data, prefix, fam, fval, rp, rq = sys.argv[1:8]
fval = int(fval)
steiner = 'true' if fam == 'st' else 'false'
famc = '.st' if fam == 'st' else '.reg'
mdir = os.path.join(proj, *prefix.split('.'))
os.makedirs(mdir, exist_ok=True)
case = f'(S43.mkCase {steiner} {fval})'
rho = f'(S43.DI.ofRat {rp} {rq})'
def h(path):
    return fnv1a(open(os.path.join(proj, path), 'rb').read())
skel = f'{data}/skel.txt'
with open(os.path.join(mdir, 'Skel.lean'), 'w') as f:
    f.write(f'import S43Data.Loader\n\n/-! skeleton of the case (generated by tools/gen_lean43.py) -/\n\n'
            f'load_cert_chunk {prefix}.skel "{skel}" {h(skel)}\n')
ranges = [tuple(map(int, l.split()[:2])) for l in open(os.path.join(proj, data, 'ranges.txt'))]
for k, (j0, n) in enumerate(ranges):
    sh = f'{data}/shard_{k:05d}.txt'
    with open(os.path.join(mdir, f'Shard{k:05d}.lean'), 'w') as f:
        f.write(f'import S43Core.Tree\nimport S43Data.Loader\nimport {prefix}.Skel\n\n'
                f'/-! shard {k}: jobs {j0} .. {j0 + n - 1} (generated by tools/gen_lean43.py) -/\n\n'
                f'load_cert_chunk {prefix}.shard{k:05d} "{sh}" {h(sh)}\n\n'
                f'theorem {prefix}.ok{k:05d} : S43.shardOKPar {case} {rho} (S43.Codes.ofString {prefix}.skel)\n'
                f'    (S43.Codes.ofString {prefix}.shard{k:05d}) {j0} {n} = true := by native_decide\n')
njobs = ranges[-1][0] + ranges[-1][1]
imports = ''.join(f'import {prefix}.Shard{k:05d}\n' for k in range(len(ranges)))
hall = ', '.join(f'⟨_, {prefix}.ok{k:05d}⟩' for k in range(len(ranges)))
rl = ', '.join(f'({j0}, {n})' for j0, n in ranges)
with open(os.path.join(mdir, 'Case.lean'), 'w') as f:
    f.write(f"""import S43.Sound.Case
import S43.Sound.Data
{imports}
/-! The case ({fam}, fval {fval}) at rho = {rp}/{rq} from its skeleton and {len(ranges)} shards (generated by
tools/gen_lean43c.py). -/

namespace {prefix}
open S43

-- hundreds of shards: the range list and the shard facts are deep terms
set_option maxRecDepth 100000

theorem mono : monoCheck {famc} {fval} = true := by native_decide
theorem skelSome : (skelBoxes {case} (Codes.ofString skel)).isSome = true := by native_decide
theorem skelN : skelSize {case} (Codes.ofString skel) = {njobs} := by native_decide

def ranges : List (ℕ × ℕ) := [{rl}]

theorem hcont : contig ranges 0 {njobs} = true := by decide

theorem hall : List.Forall (fun r : ℕ × ℕ => ∃ cs, shardOKPar {case} {rho} (Codes.ofString skel) cs r.1 r.2 = true)
    ranges :=
  ⟨{hall}⟩

theorem rho_enc : (DI.ofRat {rp} {rq}).Enc ({rp} / {rq}) := by
  have := enc_ofRat {rp} (q := {rq}) (by norm_num); push_cast at this; exact this

theorem case : CaseOK {famc} {fval} ({rp} / {rq}) :=
  case_good (F := {famc}) (fval := {fval}) (by decide) rho_enc (by norm_num) (by norm_num) (monoData_of_check mono)
    (skel := Codes.ofString skel) ranges (by rw [show caseOf {famc} {fval} = {case} from rfl, skelN]; exact hcont)
    (fun r hr => List.forall_iff_forall_mem.mp hall r hr) skelSome

end {prefix}
""")
print('wrote', len(ranges), 'shards,', njobs, 'jobs, in', mdir)
